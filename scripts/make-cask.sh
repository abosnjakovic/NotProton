#!/bin/sh
# Write the Homebrew cask for a published release to stdout.
#
# This repo is its own tap, so Casks/notproton.rb is generated here and
# committed by .github/workflows/release.yml once the release zip exists.
# Edit this script, never the cask: a release overwrites the cask.
#
#   scripts/make-cask.sh 1.1.3 "$(shasum -a 256 out/NotProton.zip | cut -d' ' -f1)" owner/repo
set -eu

if [ $# -ne 3 ]; then
	echo "usage: $0 VERSION SHA256 OWNER/REPO" >&2
	exit 1
fi

version=$1
sha256=$2
repo=$3

case $version in
	*[!0-9.]* | "" | *..*) echo "version wants digits and dots, got '$version'" >&2; exit 1 ;;
esac

case $sha256 in
	*[!0-9a-f]* | "") echo "sha256 wants lowercase hex, got '$sha256'" >&2; exit 1 ;;
esac

if [ ${#sha256} -ne 64 ]; then
	echo "sha256 wants 64 characters, got ${#sha256}" >&2
	exit 1
fi

case $repo in
	*/*) ;;
	*) echo "repo wants owner/repo, got '$repo'" >&2; exit 1 ;;
esac

# #{version} and #{appdir} are Ruby interpolation the cask resolves at install
# time, not shell expansion: this heredoc only fills in the three arguments.
cat <<EOF
# Generated by scripts/make-cask.sh. Edit that script, not this file.
cask "notproton" do
  version "$version"
  sha256 "$sha256"

  url "https://github.com/$repo/releases/download/v#{version}/NotProton.zip"
  name "NotProton"
  desc "Steam Play for the Steam client"
  homepage "https://github.com/$repo"

  livecheck do
    url :url
    strategy :github_latest
  end

  # Sparkle updates the app in place from the appcast in each release
  auto_updates true
  depends_on arch: :arm64
  depends_on macos: :tahoe

  app "NotProton.app"

  uninstall quit: "com.notproton.NotProton"

  zap trash: [
    "~/Library/Application Support/notproton",
    "~/Library/Caches/com.notproton.NotProton",
    "~/Library/Caches/notproton",
    "~/Library/HTTPStorages/com.notproton.NotProton",
    "~/Library/Preferences/com.notproton.NotProton.plist",
  ]

  caveats <<~EOS
    NotProton is ad-hoc signed, so Gatekeeper rejects a quarantined copy.
    If the app refuses to open, clear the flag:

      xattr -dr com.apple.quarantine #{appdir}/NotProton.app

    NotProton drives the macOS Steam client and installs its own CrossOver
    runner under ~/Library/Application Support/notproton on first launch.
  EOS
end
EOF
